#!/usr/bin/env python3
"""Read results/ncu/<kernel>.ncu-rep and write results/ncu_summary.md.

Uses `ncu --import <rep> --csv --page raw`, which prints one row per profiled
kernel launch with one column per collected metric (row 2 holds the units).
Every number in the output comes straight from those columns; nothing is
estimated. A missing report/metric is written as TODO, never guessed.
"""
import argparse
import csv
import io
import os
import re
import subprocess
import sys

KERNELS = ["naive", "coalesced", "smem_tiled", "reg_blocked", "vectorized"]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

M_DUR = "gpu__time_duration.sum"
M_DRAM = "dram__throughput.avg.pct_of_peak_sustained_elapsed"
M_L2 = "lts__throughput.avg.pct_of_peak_sustained_elapsed"
M_OCC = "sm__warps_active.avg.pct_of_peak_sustained_active"
M_REG = "launch__registers_per_thread"
M_BC_LD = "l1tex__data_bank_conflicts_pipe_lsu_mem_shared_op_ld.sum"
M_BC_ST = "l1tex__data_bank_conflicts_pipe_lsu_mem_shared_op_st.sum"
STALL_RE = re.compile(r"^smsp__average_warps_issue_stalled_(.+)_per_issue_active\.ratio$")


def num(s):
    try:
        return float(str(s).replace(",", "").strip())
    except ValueError:
        return None


def load_raw(rep):
    """Return ({metric: value_string}, {metric: unit}) for the first kernel row, or None."""
    out = subprocess.run(["ncu", "--import", rep, "--csv", "--page", "raw"],
                         capture_output=True, text=True)
    if out.returncode != 0:
        return None
    lines = out.stdout.splitlines()
    start = next((i for i, l in enumerate(lines) if l.startswith('"ID"')), None)
    if start is None:
        return None
    rows = list(csv.reader(io.StringIO("\n".join(lines[start:]))))
    if len(rows) < 3:
        return None
    header, units, data = rows[0], rows[1], rows[2]
    return dict(zip(header, data)), dict(zip(header, units))


def fmt(vals, name, digits=2, unit_override=None):
    v = vals.get(name)
    n = None if v is None else num(v)
    return "TODO" if n is None else (f"{n:.{digits}f}" + (unit_override or ""))


def duration_ms(vals, units):
    n = num(vals.get(M_DUR, ""))
    if n is None:
        return "TODO"
    scale = {"ns": 1e-6, "nsecond": 1e-6, "us": 1e-3, "usecond": 1e-3,
             "ms": 1.0, "msecond": 1.0, "s": 1e3, "second": 1e3}.get(units.get(M_DUR, "").strip(), None)
    return "TODO" if scale is None else f"{n * scale:.3f}"


def top_stalls(vals, k=3):
    stalls = []
    for name, v in vals.items():
        m = STALL_RE.match(name)
        n = num(v) if m else None
        if m and n is not None:
            stalls.append((n, m.group(1)))
    stalls.sort(reverse=True)
    if not stalls:
        return "TODO"
    return ", ".join(f"{name} ({n:.2f})" for n, name in stalls[:k])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", default="2048")
    args = ap.parse_args()

    rows, details = [], []
    for k in KERNELS:
        rep = next((p for p in (os.path.join(ROOT, "results", "ncu", f"{k}{e}") for e in (".ncu-rep", ".ncu-repz")) if os.path.exists(p)), "")
        raw = load_raw(rep) if os.path.exists(rep) else None
        if raw is None:
            rows.append(f"| {k} | " + " | ".join(["TODO"] * 7) + " |")
            details.append(f"- **{k}**: TODO (no readable report at `results/ncu/{k}.ncu-rep`)")
            continue
        vals, units = raw
        conflicts = [num(vals.get(M_BC_LD, "")), num(vals.get(M_BC_ST, ""))]
        bc_ld = "TODO" if conflicts[0] is None else f"{conflicts[0]:,.0f}"
        bc_st = "TODO" if conflicts[1] is None else f"{conflicts[1]:,.0f}"
        rows.append("| {} | {} | {} | {} | {} | {} | {} | {} |".format(
            k, duration_ms(vals, units), fmt(vals, M_DRAM, 1), fmt(vals, M_L2, 1),
            fmt(vals, M_OCC, 1), fmt(vals, M_REG, 0), bc_ld, bc_st))
        details.append(f"- **{k}**: {top_stalls(vals)}")

    md = f"""# Nsight Compute summary (N = {args.n})

Generated by `scripts/ncu_summary.py` from `results/ncu/*.ncu-rep`. Values are exactly what
ncu reported on this machine; `TODO` means the metric/report was not available.

| Kernel | Duration (ms) | DRAM throughput (% of peak) | L2 throughput (% of peak) | Achieved occupancy (% active warps) | Registers / thread | Shared bank conflicts (ld) | Shared bank conflicts (st) |
|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + """

## Top warp stall reasons

Metric: `smsp__average_warps_issue_stalled_<reason>_per_issue_active.ratio`
(average warps stalled for that reason per issued instruction; higher = bigger share of stall time).
Top three per kernel, value in parentheses:

""" + "\n".join(details) + "\n"
    out = os.path.join(ROOT, "results", "ncu_summary.md")
    with open(out, "w") as f:
        f.write(md)


if __name__ == "__main__":
    sys.exit(main())
